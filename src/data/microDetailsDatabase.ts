export function getMicroDetailsForReadyPart(readyPartType: string): MicroDetailDefinition[] {
  return Object.values(MICRO_DETAILS_DATABASE).filter((m) => m.parentPartType === readyPartType);
}

export function isMotherboardMicroDetail(partType: string): boolean {
  const item = MICRO_DETAILS_DATABASE[partType];
  return item?.parentPartType === "phone_motherboard";
}

export function isMicroDetail(partType: string, excludeMotherboard: boolean = false): boolean {
  if (!(partType in MICRO_DETAILS_DATABASE)) return false;
  if (excludeMotherboard && isMotherboardMicroDetail(partType)) return false;
  return true;
}

